local root = os.getenv("AVAHI_TEST_ROOT") or "files"
local model = dofile(root .. "/usr/lib/lua/avahi-ui/model.lua")
local schema = dofile(arg[1])
local passed = 0
local function check(name, condition) assert(condition, name); passed = passed + 1 end
local function valid(value) return model.validate(value, schema, function(v) return v == "192.168.8.1" or v == "::1" end) end
local raw = "# untouched\n[server]\n#host-name=example\nuse-ipv4=yes\nuse-ipv6=yes\ncustom-option=keep\n\n[reflector]\nenable-reflector=no\n[rlimits]\nrlimit-core=0\n"
check("unchanged full settings are byte identical", model.update(raw, model.settings(raw, schema)) == raw)
check("empty patch is byte identical", model.update(raw, {}) == raw)
local updated = model.update(raw, {server = {["host-name"] = "router", ["use-ipv6"] = "no"}})
check("changed existing value", model.read(updated).server["use-ipv6"] == "no")
check("append absent value", model.read(updated).server["host-name"] == "router")
check("comments retained", updated:find("#host-name=example", 1, true))
check("unknown option retained", updated:find("custom-option=keep", 1, true))
check("unknown rlimits retained", model.read(updated).rlimits["rlimit-core"] == "0")
check("remove override", model.read(model.update(raw, {server = {["use-ipv4"] = ""}})).server["use-ipv4"] == nil)
check("new section", model.read(model.update(raw, {publish = {["publish-addresses"] = "no"}})).publish["publish-addresses"] == "no")
check("do not create empty sections", model.update(raw, {publish = {["publish-addresses"] = ""}}) == raw)
local duplicates = "[server]\nhost-name=old\nhost-name=last\n"
check("first duplicate wins as in Avahi", model.read(duplicates).server["host-name"] == "old")
check("changed duplicate collapsed", model.update(duplicates, {server = {["host-name"] = "new"}}) == "[server]\nhost-name=new\n")
check("all duplicates removed", model.update(duplicates, {server = {["host-name"] = ""}}) == "[server]\n")
local crlf = raw:gsub("\n", "\r\n")
check("CRLF read", model.read(crlf).server["use-ipv4"] == "yes")
check("CRLF unchanged", model.update(crlf, model.settings(crlf, schema)) == crlf)
local crlf_changed = model.update(crlf, {server = {["use-ipv4"] = "no"}})
check("CRLF retained after update", not crlf_changed:gsub("\r\n", ""):find("\n", 1, true))
check("no final newline unchanged", model.update("[server]\nhost-name=foo", {}) == "[server]\nhost-name=foo")
check("valid interface list", valid({server = {["allow-interfaces"] = "br-lan,eth1,wlan0.1"}}))
check("valid DNS addresses", valid({publish = {["publish-dns-servers"] = "192.168.8.1,::1"}}))
check("full current settings valid", valid(model.settings(raw, schema)))
check("unknown section rejected", not valid({evil = {}}))
check("unknown key rejected", not valid({server = {evil = "yes"}}))
check("wrong type rejected", not valid({server = {["host-name"] = {}}}))
check("newline rejected", not valid({server = {["host-name"] = "foo\nuse-ipv6=no"}}))
check("NUL rejected", not valid({server = {["host-name"] = "foo\0bar"}}))
check("bad bool rejected", not valid({server = {["use-ipv4"] = "1"}}))
check("hostname with dot rejected", not valid({server = {["host-name"] = "foo.local"}}))
check("bad domain rejected", not valid({server = {["domain-name"] = "a..b"}}))
check("shell payload rejected", not valid({server = {["allow-interfaces"] = "$(reboot)"}}))
check("empty list item rejected", not valid({server = {["allow-interfaces"] = "br-lan,,eth1"}}))
check("negative limit rejected", not valid({rlimits = {["rlimit-core"] = "-1"}}))
check("overflow limit rejected", not valid({rlimits = {["rlimit-core"] = "9999999999999"}}))
check("invalid IP rejected", not valid({publish = {["publish-dns-servers"] = "999.1.1.1"}}))
check("defaults retained", model.effective({}, schema).server["use-ipv4"] == "yes")
check("case-insensitive keys", model.read("[SERVER]\nUSE-IPV4=no\n").server["use-ipv4"] == "no")
check("case-insensitive update", model.update("[SERVER]\nUSE-IPV4=no\n", {server = {["use-ipv4"] = "yes"}}) == "[SERVER]\nuse-ipv4=yes\n")
check("header comments", model.read("[server] # comment\nuse-ipv4=no\n").server["use-ipv4"] == "no")
check("repeated sections", model.update("[server]\nhost-name=old\n[server]\nhost-name=other\n", {server = {["host-name"] = "new"}}) == "[server]\nhost-name=new\n[server]\n")
check("overlong INI line rejected", not valid({server = {["allow-interfaces"] = string.rep("eth0,", 50) .. "eth1"}}))
print(passed .. " model checks passed")
